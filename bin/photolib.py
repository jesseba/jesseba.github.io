"""Shared helpers for the photo importers (import-photos, import-flickr).

Manifest files in _data/photos/ are written only by these scripts, so a small
hand-rolled YAML reader/writer is enough and keeps the toolchain free of a
PyYAML dependency. The emitted format is Prettier-clean, which matters because
CI runs `prettier . --check` across the repo.

Entries are source-agnostic. Local imports carry `file`; Flickr imports carry
`src`/`thumb`/`page`. _includes/photo_grid.liquid resolves whichever is present.
"""

import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG_ROOT = os.path.join(REPO, "assets", "img", "photography")
DATA_DIR = os.path.join(REPO, "_data", "photos")
COLLECTIONS = os.path.join(REPO, "_data", "photography.yml")

# Emission order; only fields actually present on an entry are written.
FIELD_ORDER = ["id", "file", "src", "thumb", "page", "location", "caption"]
NUMERIC = ["w", "h", "tw", "th", "ar"]

_FIELD = re.compile(r"^\s+([\w]+):\s*(.*)$")
_ENTRY = re.compile(r"^-\s+(\w+):\s*(.*)$")


def unquote(value):
    value = value.strip()
    if len(value) >= 2 and value[0] == value[-1] and value[0] in "\"'":
        return value[1:-1].replace('\\"', '"').replace("\\\\", "\\")
    return value


def quote(value):
    return '"%s"' % str(value).replace("\\", "\\\\").replace('"', '\\"')


def slugify(name, keep_ext=False):
    stem, ext = os.path.splitext(os.path.basename(name))
    stem = re.sub(r"[^a-z0-9]+", "-", stem.lower()).strip("-") or "photo"
    return stem + (ext.lower() if keep_ext else "")


def normalize_tag(value):
    """Match Flickr's 'clean' tag form: lowercased, non-alphanumerics dropped.

    A Flickr tag of "Bryce Canyon" is returned by the API as "brycecanyon", so
    location names from _data/photography.yml need the same treatment before
    they can be compared.
    """
    return re.sub(r"[^a-z0-9]+", "", str(value).lower())


def read_manifest(path):
    if not os.path.exists(path):
        return []
    entries, current = [], None
    with open(path, encoding="utf-8") as handle:
        for line in handle:
            if line.lstrip().startswith("#"):
                continue
            match = _ENTRY.match(line)
            if match:
                current = {match.group(1): unquote(match.group(2))}
                entries.append(current)
                continue
            match = _FIELD.match(line)
            if match and current is not None:
                current[match.group(1)] = unquote(match.group(2))
    return entries


def write_manifest(path, entries, slug):
    lines = [
        "# Photo manifest for '%s' — generated by bin/import-photos or bin/import-flickr." % slug,
        "#",
        "# Captions are yours to write and are preserved across re-imports.",
        "# Keep them short: place and subject, no exposure data.",
        "# Order within this file is the order they appear on the page.",
        "",
    ]
    for entry in entries:
        first = True
        for key in FIELD_ORDER:
            if key not in entry:
                continue
            prefix = "- " if first else "  "
            lines.append("%s%s: %s" % (prefix, key, quote(entry[key])))
            first = False
        for key in NUMERIC:
            if key in entry:
                lines.append("  %s: %s" % (key, entry[key]))
        lines.append("")

    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8") as handle:
        handle.write("\n".join(lines))


def entry_key(entry):
    """Stable identity for caption carry-over across re-imports."""
    return entry.get("id") or entry.get("file") or entry.get("src")


def carry_captions(existing, fresh):
    """Copy hand-written captions from `existing` onto matching `fresh` entries."""
    captions = {entry_key(e): e.get("caption", "") for e in existing}
    for entry in fresh:
        if not entry.get("caption"):
            entry["caption"] = captions.get(entry_key(entry), "")
    return fresh


def merge(existing, fresh, location):
    """Replace one location's entries in place, leaving other locations alone."""
    fresh_keys = {entry_key(e) for e in fresh}
    kept = [
        e
        for e in existing
        if e.get("location", "") != location and entry_key(e) not in fresh_keys
    ]
    return kept + fresh


def chapters(slug):
    """Return a collection's chapters as [{"name", "tag"}, ...] in config order.

    Entries in _data/photography.yml may be either a bare string (tag derived
    from the name) or a mapping with `name` and an optional `tag`. An explicit
    tag decouples the heading from what is tagged on Flickr, so renaming a
    chapter does not orphan photos already tagged.
    """
    if not os.path.exists(COLLECTIONS):
        return None
    found, in_block, in_list = None, False, False
    with open(COLLECTIONS, encoding="utf-8") as handle:
        for raw in handle:
            line = raw.rstrip("\n")
            if line.lstrip().startswith("#"):
                continue
            if re.match(r"^-\s+slug:", line):
                in_block = unquote(line.split(":", 1)[1]) == slug
                in_list = False
                continue
            if not in_block:
                continue
            if re.match(r"^\s+locations:", line):
                in_list, found = True, []
                tail = line.split(":", 1)[1].strip()
                if tail.startswith("["):  # inline list
                    inner = tail.strip("[]").strip()
                    found = [{"name": unquote(x)} for x in inner.split(",") if x.strip()]
                    in_list = False
                continue
            if not in_list:
                continue

            item = re.match(r"^\s+-\s+(.*)$", line)
            if item:
                body = item.group(1)
                keyed = re.match(r"^name:\s*(.*)$", body)
                found.append({"name": unquote(keyed.group(1))} if keyed else {"name": unquote(body)})
                continue
            # Continuation line of the entry above, e.g. `  tag: zion`.
            field = re.match(r"^\s+(\w+):\s*(.*)$", line)
            if field and found:
                found[-1][field.group(1)] = unquote(field.group(2))
            elif line.strip():
                in_list = False

    if found is None:
        return None
    for chapter in found:
        chapter.setdefault("tag", chapter["name"])
    return found


def known_locations(slug):
    """Chapter display names, in config order."""
    found = chapters(slug)
    return None if found is None else [c["name"] for c in found]


def collection_slugs():
    slugs = []
    if not os.path.exists(COLLECTIONS):
        return slugs
    with open(COLLECTIONS, encoding="utf-8") as handle:
        for line in handle:
            match = re.match(r"^-\s+slug:\s*(.*)$", line)
            if match:
                slugs.append(unquote(match.group(1)))
    return slugs
